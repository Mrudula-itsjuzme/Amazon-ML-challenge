def get_target_signature(
    s2,
    s3,
):

    parts = [
        str(len(s2)),
        str(len(s3)),
        (
            str(s2["entity_id"].iloc[0])
            if len(s2)
            else ""
        ),
        (
            str(s2["entity_id"].iloc[-1])
            if len(s2)
            else ""
        ),
        (
            str(s3["entity_id"].iloc[0])
            if len(s3)
            else ""
        ),
        (
            str(s3["entity_id"].iloc[-1])
            if len(s3)
            else ""
        ),
    ]

    raw = "|".join(parts)

    return hashlib.md5(
        raw.encode("utf-8")
    ).hexdigest()[:16]


def char_cache_path(
    split,
    signature,
):

    return (
        CACHE_DIR
        /
        (
            f"{split}_char_index_"
            f"{signature}_v{CHAR_CACHE_VERSION}.pkl"
        )
    )


def load_or_build_char_indexes(
    targets,
    split,
    signature,
):

    cache_path = char_cache_path(
        split,
        signature,
    )

    if cache_path.exists():

        print(
            "\nLoading cached character indexes..."
        )

        start = time.time()

        with open(
            cache_path,
            "rb",
        ) as f:

            cache = pickle.load(f)

        print(
            f"Character indexes loaded in "
            f"{time.time() - start:.1f}s"
        )

        return (
            cache["name_index"],
            cache["name_freq"],
            cache["address_index"],
            cache["address_freq"],
        )

    print(
        "\nNo character-index cache found."
    )

    print(
        "Building character indexes..."
    )

    start = time.time()

    name_index, name_freq = (
        build_char_ngram_index(
            targets,
            "name_norm",
        )
    )

    address_index, address_freq = (
        build_char_ngram_index(
            targets,
            "address_norm",
        )
    )

    cache = {
        "name_index": name_index,
        "name_freq": name_freq,
        "address_index": address_index,
        "address_freq": address_freq,
    }

    with open(
        cache_path,
        "wb",
    ) as f:

        pickle.dump(
            cache,
            f,
            protocol=pickle.HIGHEST_PROTOCOL,
        )

    print(
        f"Character indexes built + cached in "
        f"{time.time() - start:.1f}s"
    )

    return (
        name_index,
        name_freq,
        address_index,
        address_freq,
    )


