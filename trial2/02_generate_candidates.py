def add_single_target(
    candidate_map,
    target_id,
    channel,
):

    if not target_id:
        return

    channels = candidate_map.get(
        target_id
    )

    if channels is None:

        candidate_map[target_id] = {
            channel
        }

    else:

        channels.add(channel)


def add_route_candidates(
    candidate_map,
    target_ids,
    channel,
    budget=None,
):

    if not target_ids:
        return

    if budget is not None:

        target_ids = target_ids[
            :budget
        ]

    for target_id in target_ids:

        add_single_target(
            candidate_map,
            target_id,
            channel,
        )


# ============================================================
# QUERY TOKEN SELECTION
# ============================================================

def select_query_tokens(
    value,
    frequencies,
):

    if not value:
        return []

    tokens = {
        token
        for token in value.split()
        if len(token) >= MIN_TOKEN_LENGTH
    }

    # Rarest tokens first.
    #
    # This is important:
    #
    #     "private" frequency = millions
    #     "oriental" frequency = much smaller
    #
    # We want the latter to drive retrieval.
    ranked = sorted(
        tokens,
        key=lambda token: (
            frequencies.get(
                token,
                10**18,
            ),
            -len(token),
            token,
        ),
    )

    return ranked[
        :MAX_QUERY_TOKENS
    ]


# ============================================================
# SINGLE RARE TOKEN RETRIEVAL
# ============================================================

def retrieve_rare_token_candidates(
    query_tokens,
    token_index,
    frequencies,
    budget,
):

    candidate_scores = Counter()

    for token in query_tokens:

        freq = frequencies.get(
            token,
            10**18,
        )

        # Only use genuinely selective tokens
        # as standalone blocking keys.
        if freq > MAX_RARE_SINGLE_FREQUENCY:
            continue

        postings = token_index.get(
            token,
            [],
        )

        if (
            not postings
            or
            len(postings) > MAX_RARE_POSTINGS
        ):
            continue

        rarity = 1.0 / max(
            freq,
            1,
        )

        for target_id in postings:

            candidate_scores[
                target_id
            ] += rarity

    ranked = sorted(
        candidate_scores.items(),
        key=lambda x: x[1],
        reverse=True,
    )

    return [
        target_id
        for target_id, _
        in ranked[:budget]
    ]


# ============================================================
# INTERSECTION-FIRST TOKEN RETRIEVAL
# ============================================================

def retrieve_intersection_candidates(
    query_value,
    token_index,
    frequencies,
    target_text,
    budget,
):

    if not query_value:
        return []

    query_tokens = select_query_tokens(
        query_value,
        frequencies,
    )

    if len(query_tokens) < 2:
        return []

    # --------------------------------------------------------
    # Build token posting metadata.
    #
    # We DO NOT discard common tokens here.
    #
    # We only refuse gigantic lists because intersecting
    # millions of records is pointless.
    # --------------------------------------------------------

    usable = []

    for token in query_tokens:

        postings = token_index.get(
            token,
            [],
        )

        if not postings:
            continue

        if len(postings) <= MAX_INTERSECTION_POSTINGS:

            usable.append(
                (
                    token,
                    postings,
                    frequencies.get(
                        token,
                        10**18,
                    ),
                )
            )

    if len(usable) < 2:
        return []

    # Rarest posting lists first.
    usable.sort(
        key=lambda x: len(x[1])
    )

    # --------------------------------------------------------
    # Candidate scoring.
    #
    # We don't simply use ONE pair.
    #
    # For each pair of useful tokens:
    #
    #     intersection(token_i, token_j)
    #
    # Then accumulate evidence.
    # --------------------------------------------------------

    scores = Counter()
    shared_tokens = Counter()

    max_pairs = min(
        MAX_QUERY_TOKEN_PAIRS,
        len(usable) * (len(usable) - 1) // 2,
    )

    pair_count = 0

    for i in range(
        len(usable)
    ):

        token_a, postings_a, freq_a = (
            usable[i]
        )

        set_a = set(
            postings_a
        )

        for j in range(
            i + 1,
            len(usable),
        ):

            if pair_count >= max_pairs:
                break

            token_b, postings_b, freq_b = (
                usable[j]
            )

            # Always iterate over the smaller list.
            if len(postings_a) <= len(postings_b):

                smaller = postings_a
                larger = set(
                    postings_b
                )

            else:

                smaller = postings_b
                larger = set_a

            pair_count += 1

            pair_weight = (
                1.0
                /
                max(
                    min(
                        freq_a,
                        freq_b,
                    ),
                    1,
                )
            )

            for target_id in smaller:

                if target_id not in larger:
                    continue

                shared_tokens[
                    target_id
                ] += 1

                scores[
                    target_id
                ] += pair_weight

    if not scores:
        return []

    # --------------------------------------------------------
    # SECONDARY SCORING
    #
    # For candidates retrieved by intersections, inspect
    # actual target token overlap.
    # --------------------------------------------------------

    query_set = set(
        query_tokens
    )

    ranked = []

    for target_id, retrieval_score in (
        scores.items()
    ):

        target_value = target_text.get(
            target_id,
            "",
        )

        if not target_value:
            continue

        target_tokens = set(
            target_value.split()
        )

        overlap = len(
            query_set
            &
            target_tokens
        )

        if overlap <= 0:
            continue

        # Shared-token count dominates.
        #
        # Rarity is a secondary signal.
        final_score = (
            100.0 * overlap
            +
            10.0 * shared_tokens[target_id]
            +
            retrieval_score
        )

        ranked.append(
            (
                final_score,
                overlap,
                shared_tokens[target_id],
                target_id,
            )
        )

    ranked.sort(
        reverse=True
    )

    return [
        target_id
        for _, _, _, target_id
        in ranked[:budget]
    ]


# ============================================================
# POSTAL + NAME
# ============================================================

def retrieve_postal_name(
    postal,
    name_tokens,
    postal_index,
    target_name_text,
    budget,
):

    if not postal:
        return []

    ids = postal_index.get(
        postal,
        [],
    )

    if not ids:
        return []

    query_tokens = set(
        name_tokens
    )

    scored = []

    for target_id in ids:

        name = target_name_text.get(
            target_id,
            "",
        )

        if not name:
            continue

        shared = (
            query_tokens
            &
            set(name.split())
        )

        if not shared:
            continue

        scored.append(
            (
                len(shared),
                target_id,
            )
        )

    scored.sort(
        reverse=True
    )

    return [
        target_id
        for _, target_id
        in scored[:budget]
    ]


# ============================================================
# NUMBER RETRIEVAL
# ============================================================

def retrieve_number_candidates(
    numbers,
    number_index,
    budget,
):

    if not numbers:
        return []

    counts = Counter()

    for number in numbers:

        postings = number_index.get(
            number,
            [],
        )

        # Avoid a number like "1" or common building
        # number exploding the candidate set.
        if (
            not postings
            or
            len(postings) > MAX_INTERSECTION_POSTINGS
        ):
            continue

        for target_id in postings:

            counts[target_id] += 1

    ranked = sorted(
        counts.items(),
        key=lambda x: (
            x[1],
        ),
        reverse=True,
    )

    return [
        target_id
        for target_id, _
        in ranked[:budget]
    ]


# ============================================================
# NUMBER + ADDRESS TOKEN
# ============================================================

def retrieve_number_address_candidates(
    numbers,
    address_tokens,
    number_index,
    target_address_text,
    budget,
):

    number_candidates = (
        retrieve_number_candidates(
            numbers,
            number_index,
            MAX_ROUTE_POOL,
        )
    )

    if not number_candidates:
        return []

    address_set = set(
        address_tokens
    )

    scored = []

    for target_id in number_candidates:

        address = target_address_text.get(
            target_id,
            "",
        )

        if not address:
            continue

        target_tokens = set(
            address.split()
        )

        shared = (
            address_set
            &
            target_tokens
        )

        if not shared:
            continue

        scored.append(
            (
                len(shared),
                target_id,
            )
        )

    scored.sort(
        reverse=True
    )

    return [
        target_id
        for _, target_id
        in scored[:budget]
    ]


# ============================================================
# CHARACTER RETRIEVAL
# ============================================================

def retrieve_char_candidates(
    query,
    char_index,
    char_freq,
    budget,
):

    if not query:
        return []

    query_grams = set(
        make_char_grams(query)
    )

    if not query_grams:
        return []

    useful = [
        gram
        for gram in query_grams
        if gram in char_index
    ]

    if not useful:
        return []

    useful.sort(
        key=lambda gram:
        char_freq.get(
            gram,
            10**18,
        )
    )

    useful = useful[
        :MAX_QUERY_CHAR_GRAMS
    ]

    counts = Counter()

    for gram in useful:

        postings = char_index.get(
            gram,
            [],
        )

        if not postings:
            continue

        for target_id in postings:

            counts[target_id] += 1

    if not counts:
        return []

    ranked = sorted(
        counts.items(),
        key=lambda x: (
            x[1],
        ),
        reverse=True,
    )

    strong = [
        target_id
        for target_id, count
        in ranked
        if count >= MIN_SHARED_CHAR_GRAMS
    ]

    if strong:

        return strong[
            :budget
        ]

    return [
        target_id
        for target_id, _
        in ranked[:budget]
    ]


# ============================================================
# BOUNDED FUZZY RETRIEVAL
# ============================================================

def bounded_fuzzy_retrieve(
    query,
    target_ids,
    target_text,
    budget,
    score_cutoff,
    candidate_map,
    channel,
):

    if not query or not target_ids:
        return

    target_ids = list(
        dict.fromkeys(
            target_ids
        )
    )

    if len(target_ids) > MAX_ROUTE_POOL:

        target_ids = target_ids[
            :MAX_ROUTE_POOL
        ]

    valid_pairs = []

    for target_id in target_ids:

        text = target_text.get(
            target_id,
            "",
        )

        if text:

            valid_pairs.append(
                (
                    target_id,
                    text,
                )
            )

    if not valid_pairs:
        return

    choices = [
        text
        for _, text
        in valid_pairs
    ]

    matches = process.extract(
        query,
        choices,
        scorer=fuzz.WRatio,
        score_cutoff=score_cutoff,
        limit=budget,
    )

    for _, score, index in matches:

        if (
            0
            <= index
            <
            len(valid_pairs)
        ):

            target_id = valid_pairs[
                index
            ][0]

            add_single_target(
                candidate_map,
                target_id,
                channel,
            )


# ============================================================
# FINAL CANDIDATE CAP
# ============================================================

def cap_candidate_map(
    candidate_map,
    max_candidates=MAX_CANDIDATES_PER_ENTITY,
):

    if len(candidate_map) <= max_candidates:
        return candidate_map

    def candidate_rank(item):

        target_id, channels = item

        route_scores = sorted(
            [
                ROUTE_PRIORITY.get(
                    channel,
                    0,
                )
                for channel in channels
            ],
            reverse=True,
        )

        strongest = (
            route_scores[0]
            if route_scores
            else 0
        )

        second = (
            route_scores[1]
            if len(route_scores) > 1
            else 0
        )

        evidence_score = (
            strongest
            +
            0.35 * second
            +
            0.20 * sum(
                route_scores[2:]
            )
        )

        return (
            evidence_score,
            len(channels),
            strongest,
        )

    ranked = sorted(
        candidate_map.items(),
        key=candidate_rank,
        reverse=True,
    )

    return dict(
        ranked[
            :max_candidates
        ]
    )


