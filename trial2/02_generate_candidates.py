# ============================================================
# HELPERS
# ============================================================

def clean_tokens(value):

    if not value:
        return []

    return list({
        token
        for token in value.split()
        if len(token) >= MIN_TOKEN_LENGTH
    })


def make_char_grams(value):

    if not value:
        return []

    value = value.strip()

    if len(value) < CHAR_GRAM_N:
        return []

    return list({
        value[i:i + CHAR_GRAM_N]
        for i in range(
            len(value) - CHAR_GRAM_N + 1
        )
    })


# ============================================================
# EXACT INDEX
# ============================================================

def build_exact_index(df, column):

    index = defaultdict(list)

    for entity_id, value in zip(
        df["entity_id"],
        df[column],
    ):

        if value:
            index[value].append(entity_id)

    return index


# ============================================================
# TOKEN POSTING INDEX
# ============================================================

def build_token_index(
    df,
    column,
):

    print(
        f"  Building token index for {column}..."
    )

    index = defaultdict(list)
    frequencies = Counter()

    # --------------------------------------------------------
    # Frequency pass
    # --------------------------------------------------------

    for value in df[column]:

        if not value:
            continue

        for token in set(
            value.split()
        ):

            if len(token) >= MIN_TOKEN_LENGTH:

                frequencies[token] += 1

    print(
        f"  {column}: "
        f"{len(frequencies):,} unique tokens"
    )

    # --------------------------------------------------------
    # Posting pass
    # --------------------------------------------------------

    for entity_id, value in zip(
        df["entity_id"],
        df[column],
    ):

        if not value:
            continue

        for token in set(
            value.split()
        ):

            if len(token) < MIN_TOKEN_LENGTH:
                continue

            if frequencies[token] <= MAX_TOKEN_FREQUENCY:

                index[token].append(
                    entity_id
                )

    return index, frequencies


# ============================================================
# PREFIX INDEX
# ============================================================

def build_prefix_index(
    df,
    column,
):

    index = defaultdict(list)

    for entity_id, value in zip(
        df["entity_id"],
        df[column],
    ):

        if not value:
            continue

        compact = value.replace(
            " ",
            "",
        )

        if len(compact) < NAME_PREFIX_LENGTH:
            continue

        prefix = compact[
            :NAME_PREFIX_LENGTH
        ]

        index[prefix].append(
            entity_id
        )

    return index


# ============================================================
# CHARACTER N-GRAM INDEX
# ============================================================

def build_char_ngram_index(
    df,
    column,
):

    print(
        f"  Character index: frequency pass "
        f"for {column}..."
    )

    frequencies = Counter()

    for value in df[column]:

        if not value:
            continue

        frequencies.update(
            set(
                make_char_grams(value)
            )
        )

    useful_grams = {
        gram
        for gram, freq in frequencies.items()
        if (
            CHAR_GRAM_MIN_FREQ
            <= freq
            <= CHAR_GRAM_MAX_FREQ
        )
    }

    print(
        f"  {column}: "
        f"{len(frequencies):,} total grams -> "
        f"{len(useful_grams):,} selective grams"
    )

    index = defaultdict(list)

    for entity_id, value in zip(
        df["entity_id"],
        df[column],
    ):

        if not value:
            continue

        for gram in set(
            make_char_grams(value)
        ):

            if gram in useful_grams:

                index[gram].append(
                    entity_id
                )

    return (
        index,
        {
            gram: frequencies[gram]
            for gram in useful_grams
        },
    )


