def load_source_data():

    print("\nLoading source data...")

    s1 = pd.read_parquet(S1_PATH)

    s2 = pd.read_parquet(S2_PATH)

    s3 = pd.read_parquet(S3_PATH)

    candidate_source = pd.concat(
        [
            s2,
            s3
        ],
        ignore_index=True
    )

    # Avoid column-name collisions after merging.

    source_columns = [
        "entity_id",
        "business_name",
        "business_address",
        "country",
        "name_norm",
        "name_core",
        "name_translit",
        "address_norm",
        "postal_code",
        "numeric_tokens",
        "country_norm",
    ]

    source_columns = [
        c
        for c in source_columns
        if c in s1.columns
        and c in candidate_source.columns
    ]

    s1 = s1[
        source_columns
    ].copy()

    candidate_source = candidate_source[
        source_columns
    ].copy()

    print(
        f"S1 rows : {len(s1):,}"
    )

    print(
        f"S2+S3 rows : {len(candidate_source):,}"
    )

    return s1, candidate_source


