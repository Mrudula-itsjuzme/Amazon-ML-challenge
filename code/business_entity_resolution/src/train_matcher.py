# NORMALIZATION HELPERS
# ============================================================

def safe_string(value):

    if pd.isna(value):
        return ""

    return str(value)


def token_set(text):

    text = safe_string(text)

    if not text:
        return set()

    return set(
        token
        for token in text.split()
        if token
    )


def jaccard(a, b):

    a = token_set(a)
    b = token_set(b)

    if not a and not b:
        return 1.0

    if not a or not b:
        return 0.0

    union = a | b

    if not union:
        return 0.0

    return len(a & b) / len(union)


def token_overlap(a, b):

    a = token_set(a)
    b = token_set(b)

    if not a or not b:
        return 0.0

    smaller = min(len(a), len(b))

    if smaller == 0:
        return 0.0

    return len(a & b) / smaller


def sequence_similarity(a, b):

    a = safe_string(a)
    b = safe_string(b)

    if not a and not b:
        return 1.0

    if not a or not b:
        return 0.0

    return difflib.SequenceMatcher(
        None,
        a,
        b
    ).ratio()


def length_ratio(a, b):

    a = safe_string(a)
    b = safe_string(b)

    la = len(a)
    lb = len(b)

    if la == 0 and lb == 0:
        return 1.0

    if la == 0 or lb == 0:
        return 0.0

    return min(la, lb) / max(la, lb)


def numeric_token_set(text):

    text = safe_string(text)

    if not text:
        return set()

    return set(
        token
        for token in text.split()
        if token.isdigit()
    )


def numeric_overlap(a, b):

    a = numeric_token_set(a)
    b = numeric_token_set(b)

    if not a or not b:
        return 0.0

    return len(a & b) / min(
        len(a),
        len(b)
    )


def has_numeric_overlap(a, b):

    return float(
        len(
            numeric_token_set(a)
            &
            numeric_token_set(b)
        ) > 0
    )


